  function processText(node,locale){
    const parent=node.parentElement;
    if(!parent||parent.closest('script,style,textarea,code,pre,.ol-raw-data,.ol-chat-line.ol-from-user,.ol-user-data'))return;
    const s=node.textContent;const trimmed=s.trim();if(!trimmed)return;
    const key=originals.get(node)||original(trimmed);
    // Translate known labels and recurring generated UI lines only.
    if(!originals.has(node)&&!english.has(key)&&!inverse.has(trimmed)&&!(/^(Last check-in:|Latest:|Next action:|Day \d+|No astronauts match|Viewing crew member )/.test(key))&&!/^(Commander|Flight Engineer|Medical Officer|Pilot|Systems Engineer|Botanist|Mission Scientist|Geologist|Payload Specialist|Researcher)\s*[·-]/.test(key))return;
    originals.set(node,key);
    const translated=translateDynamic(textIn(key,locale),locale);
    const prefix=s.match(/^\s*/)[0],suffix=s.match(/\s*$/)[0];
    const result=prefix+translated+suffix;
    if(s!==result)node.textContent=result;
  }
  function processAttrs(node,locale){
    if(!node.hasAttribute||node.closest('.ol-raw-data'))return;
    for(const attr of ['placeholder','title','aria-label']){
      const current=node.getAttribute(attr);if(!current)continue;
      let cache=attrs.get(node)||{};
      const key=cache[attr]||original(current);
      if(!cache[attr]&&(english.has(key)||inverse.has(current)))cache[attr]=key;
      if(cache[attr]){
        const translated=textIn(key,locale);
        if(current!==translated)node.setAttribute(attr,translated);
        attrs.set(node,cache);
      }
    }
  }
